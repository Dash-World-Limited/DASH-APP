/**
 * The DASH wordmark: the approved all-caps mark from the director's boards.
 *
 * This is brand artwork, not text. Never type "DASH" in a header or a logo
 * position, and never set it in Manrope or any other face: render this.
 *
 * There is still no master file, so the outlines were measured from the four
 * appearances of the mark on the 13 September Customer and Rider boards. Each
 * letter was fitted as geometry to the board's own pixels and the four
 * measurements averaged; nothing was drawn by eye. The method, the numbers
 * and a side-by-side check against the boards are in
 * docs/design/boards/2026-09-13/wordmark. The outlines are in
 * wordmarkGeometry.ts, generated by the script there. When David supplies a
 * master SVG it replaces that file and nothing else changes.
 *
 * Graphite D and open A, bronze S and H, and the short bronze bar in the A's
 * counter, all as on the boards. There is no dot after DASH: that is the
 * retired mark. Dark mode changes colour only (tokens `wordmark.*`): the
 * graphite letters take the scheme's off-white and the bronze stays.
 */

import { View } from 'react-native';
import Svg, { Path } from 'react-native-svg';

import { useTheme } from '../theme/ThemeProvider';
import {
  WORDMARK_ASPECT,
  WORDMARK_BRONZE_PATH,
  WORDMARK_GRAPHITE_PATH,
  WORDMARK_VIEWBOX,
} from './wordmarkGeometry';

/**
 * Letter height of the Home headers, in points. Measured on the boards: the
 * mark's cap height is 12.9 px on a 234 px-wide Customer phone and 15.0 px on
 * a 250 px-wide Rider phone, which is 22.7 and 24.7 pt on a 411 pt-wide
 * phone such as the Samsung A55.
 */
export const HOME_HEADER_WORDMARK_HEIGHT = 24;

/** `height` is the height of the letters; the width follows the mark's proportions. */
export function Wordmark({ height = HOME_HEADER_WORDMARK_HEIGHT }: { height?: number }) {
  const { palette } = useTheme();
  const width = height * WORDMARK_ASPECT;
  return (
    <View
      accessible
      accessibilityRole="header"
      accessibilityLabel="DASH"
      style={{ width, height }}
      testID="dash-wordmark"
    >
      <Svg width={width} height={height} viewBox={WORDMARK_VIEWBOX}>
        <Path fill={palette.wordmark.lead} fillRule="evenodd" d={WORDMARK_GRAPHITE_PATH} />
        <Path fill={palette.wordmark.bronze} d={WORDMARK_BRONZE_PATH} />
      </Svg>
    </View>
  );
}
