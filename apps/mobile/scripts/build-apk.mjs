/**
 * Build an internal debug APK, reproducibly, from one command.
 *
 * There are four things this has to get right, and three of them are the kind
 * that produce an APK which installs perfectly and then does nothing:
 *
 *   1. The WebView must point at the development machine, not at `localhost`
 *      — which on a phone is the phone. `configure.mjs` refuses to build if it
 *      is not told a real address.
 *   2. Cleartext must be permitted for that machine, because the local test
 *      stack speaks plain HTTP. Android has refused cleartext by default since
 *      API 28, correctly, so the exception is written narrowly here rather
 *      than by switching the protection off for every host.
 *   3. The web client baked into the running dev server must call the API by
 *      that same address. This script cannot enforce that — the web server is
 *      started separately — so it prints the required `NEXT_PUBLIC_API_URL`
 *      and the runbook repeats it.
 *   4. The Android toolchain has to be found without assuming a developer has
 *      exported `JAVA_HOME`. Android Studio ships a JDK; this locates it.
 *
 * Debug signing only. The output is for sideloading onto a test handset and is
 * not a release artefact.
 */

import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { homedir } from 'node:os';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const android = join(root, 'android');

const host = process.env['DASH_MOBILE_HOST'];
const apiPort = process.env['DASH_MOBILE_API_PORT'] ?? '4000';

// --- 1. Capacitor config, with its own guards on the host -------------------
execFileSync(process.execPath, [join(root, 'scripts', 'configure.mjs')], {
  stdio: 'inherit',
  env: process.env,
});

// --- 2. Cleartext, for exactly one host -------------------------------------
//
// Regenerated on every build so the permitted host cannot drift away from the
// host the WebView was pointed at — a mismatch between the two is invisible
// until the app is on a phone, where it looks like the server is down.
const networkSecurityConfig = `<?xml version="1.0" encoding="utf-8"?>
<!--
  GENERATED by apps/mobile/scripts/build-apk.mjs — do not edit by hand.

  Cleartext HTTP for the local test backend, and for nothing else.

  Android has blocked cleartext by default since API 28. That protection is
  not switched off here. Capacitor offers \`cleartext: true\`, but it sets
  \`usesCleartextTraffic\` application-wide, which would let this build talk
  plaintext to any host on the internet — too broad a concession for the sake
  of reaching one development server.

  The base configuration therefore still refuses cleartext, and a single
  domain exception is granted to the machine this APK was built against.
  Everything else continues to require TLS.

  Debug shell only. A release build must not contain this file.
-->
<network-security-config>
    <base-config cleartextTrafficPermitted="false">
        <trust-anchors>
            <certificates src="system" />
        </trust-anchors>
    </base-config>

    <domain-config cleartextTrafficPermitted="true">
        <!-- The development machine this build was pointed at. -->
        <domain includeSubdomains="false">${host}</domain>
        <!-- The shell's own bundled page. The android scheme is http so the
             launcher can probe an http server without tripping mixed-content,
             so localhost has to be permitted as well. Requests to it never
             leave the device: Capacitor serves them from the APK. -->
        <domain includeSubdomains="false">localhost</domain>
    </domain-config>
</network-security-config>
`;

// --- 2b. A build stamp, so an installed APK can identify itself ------------
//
// Diagnosing "is the phone running the new build?" from download logs is
// guesswork. Android shows `versionName` in App info, and the launcher page
// shows it too, so the question has a direct answer.
//
// Passed to Gradle as a property rather than written into `build.gradle`.
// Rewriting that file left every build with a modified tracked file, so
// `git status` was never clean after building and whichever timestamp was
// committed belonged to whoever built last.
const stamp = new Date().toISOString().slice(0, 16).replace('T', ' ');
const versionName = `test-${stamp.replace(/[: ]/g, '')}`;
console.warn(`build stamp ${stamp}`);

const xmlDir = join(android, 'app', 'src', 'main', 'res', 'xml');
mkdirSync(xmlDir, { recursive: true });
writeFileSync(join(xmlDir, 'network_security_config.xml'), networkSecurityConfig);
console.warn(`cleartext permitted for ${host} only`);

// --- 3. Toolchain -----------------------------------------------------------
function findJdk() {
  // A JDK this project vendors for itself, checked first.
  //
  // Android Studio ships JDK 25, which Gradle 8 refuses ("unsupported class
  // file major version 69"). Moving to Gradle 9 to satisfy it forces AGP 9,
  // and AGP 9 removed the Groovy DSL that Capacitor 7's own plugins are
  // written against — so the geolocation plugin would not build at all. A
  // JDK 21 puts the whole toolchain back on the combination Capacitor
  // actually supports, and costs one folder rather than a patched vendor file.
  const vendored = join(root, '..', '..', '.tooling');
  if (existsSync(vendored)) {
    const jdk = readdirSync(vendored).find((name) => name.startsWith('jdk-21'));
    if (jdk) return join(vendored, jdk);
  }
  if (process.env['JAVA_HOME']) return process.env['JAVA_HOME'];
  const candidates = [
    join(process.env['ProgramFiles'] ?? 'C:\\Program Files', 'Android', 'Android Studio', 'jbr'),
    '/Applications/Android Studio.app/Contents/jbr/Contents/Home',
    join(homedir(), '.jdks'),
  ];
  const found = candidates.find((path) => existsSync(join(path, 'bin', 'java.exe')) || existsSync(join(path, 'bin', 'java')));
  if (!found) {
    throw new Error(
      'No JDK found. Set JAVA_HOME, or install Android Studio, which ships one.',
    );
  }
  return found;
}

function findSdk() {
  const fromEnv = process.env['ANDROID_HOME'] ?? process.env['ANDROID_SDK_ROOT'];
  if (fromEnv) return fromEnv;
  const candidates = [
    join(process.env['LOCALAPPDATA'] ?? '', 'Android', 'Sdk'),
    join(homedir(), 'Library', 'Android', 'sdk'),
    join(homedir(), 'Android', 'Sdk'),
  ];
  const found = candidates.find((path) => path && existsSync(path));
  if (!found) throw new Error('No Android SDK found. Set ANDROID_HOME.');
  return found;
}

const javaHome = findJdk();
const sdk = findSdk();
console.warn(`JDK ${javaHome}`);
console.warn(`SDK ${sdk}`);

// Gradle reads the SDK location from here when ANDROID_HOME is not exported
// into its own environment.
writeFileSync(join(android, 'local.properties'), `sdk.dir=${sdk.replace(/\\/g, '\\\\')}\n`);

const env = { ...process.env, JAVA_HOME: javaHome, ANDROID_HOME: sdk };

// --- 4. Sync and build ------------------------------------------------------
const capacitorCli = join(root, '..', '..', 'node_modules', '@capacitor', 'cli', 'bin', 'capacitor');
execFileSync(process.execPath, [capacitorCli, 'sync', 'android'], { cwd: root, stdio: 'inherit', env });

// Absolute path: a bare `gradlew.bat` is not resolved from the working
// directory by the Windows shell, and the failure looks like a missing
// toolchain rather than a missing `.\`.
const gradlew = join(android, process.platform === 'win32' ? 'gradlew.bat' : 'gradlew');
execFileSync(gradlew, ['assembleDebug', '--no-daemon', `-PdashVersionName=${versionName}`], {
  cwd: android,
  stdio: 'inherit',
  env,
  shell: process.platform === 'win32',
});

const apk = join(android, 'app', 'build', 'outputs', 'apk', 'debug', 'app-debug.apk');
console.warn('');
console.warn('APK ready');
console.warn(`  ${apk}`);
console.warn('');
console.warn('Before installing, start the stack bound to the network:');
console.warn(`  API_HOST=0.0.0.0 PUBLIC_WEB_URL=http://${host}:3000 npm run dev:api`);
console.warn(`  NEXT_PUBLIC_API_URL=http://${host}:${apiPort} npm run dev:web`);
